-- SCRIPT SQL LENGKAP: SKEMA DATABASE SAKUIN (DOMPET & CELENGAN PELAJAR)
-- Platform: Supabase PostgreSQL (Siap dijalankan di SQL Editor)
-- Sifat: Idempotent (Aman dijalankan berkali-kali tanpa duplikasi/error)
