-- 1. TABEL `public.dompet_pelajar`
-- Menyimpan saldo aktif (sisa saku & celengan) serta checklist rutin untuk setiap user Google.
CREATE TABLE IF NOT EXISTS public.dompet_pelajar (
    user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    sisa_saku BIGINT NOT NULL DEFAULT 0,
    total_celengan BIGINT NOT NULL DEFAULT 0,
    target_celengan BIGINT NOT NULL DEFAULT 100000,
    nama_target_celengan TEXT NOT NULL DEFAULT 'Beli Barang Impian',
    kas_senin_lunas BOOLEAN NOT NULL DEFAULT false,
    bawa_bekal_hari_ini BOOLEAN NOT NULL DEFAULT false,
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- Kolom tambahan untuk target impian (aman jika tabel sudah ada)
ALTER TABLE public.dompet_pelajar 
    ADD COLUMN IF NOT EXISTS target_celengan BIGINT NOT NULL DEFAULT 100000,
    ADD COLUMN IF NOT EXISTS nama_target_celengan TEXT NOT NULL DEFAULT 'Beli Barang Impian';

-- 2. TABEL `public.riwayat_transaksi`
-- Menyimpan seluruh mutasi transaksi harian: pengeluaran jajan/ongkos/kas & alokasi celengan.
CREATE TABLE IF NOT EXISTS public.riwayat_transaksi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    tanggal TEXT NOT NULL,
    judul TEXT NOT NULL,
    nominal BIGINT NOT NULL CHECK (nominal > 0),
    tipe TEXT NOT NULL CHECK (tipe IN ('keluar', 'tabungan')),
    kategori TEXT NOT NULL CHECK (kategori IN ('Jajan', 'Ongkos', 'Kas', 'Celengan', 'Lainnya')),
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 3. INDEX PERFORMA
-- Mempercepat query pemanggilan riwayat dan filter berdasarkan user & urutan waktu terbaru di perangkat HP.
CREATE INDEX IF NOT EXISTS idx_riwayat_transaksi_user_id 
    ON public.riwayat_transaksi(user_id);

CREATE INDEX IF NOT EXISTS idx_riwayat_transaksi_created_at 
    ON public.riwayat_transaksi(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_riwayat_transaksi_user_created 
    ON public.riwayat_transaksi(user_id, created_at DESC);

-- 4. ROW LEVEL SECURITY (RLS)
-- Memastikan pengguna hanya bisa melihat, menambah, mengubah, dan menghapus data miliknya sendiri.
ALTER TABLE public.dompet_pelajar ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.riwayat_transaksi ENABLE ROW LEVEL SECURITY;

-- Idempotent Policy: Hapus policy lama jika sudah ada sebelum membuat ulang
DROP POLICY IF EXISTS "Pengguna hanya dapat melihat dompet sendiri" ON public.dompet_pelajar;
DROP POLICY IF EXISTS "Pengguna dapat membuat dompet sendiri" ON public.dompet_pelajar;
DROP POLICY IF EXISTS "Pengguna dapat memperbarui dompet sendiri" ON public.dompet_pelajar;
DROP POLICY IF EXISTS "Pengguna dapat menghapus dompet sendiri" ON public.dompet_pelajar;

DROP POLICY IF EXISTS "Pengguna hanya dapat melihat riwayat sendiri" ON public.riwayat_transaksi;
DROP POLICY IF EXISTS "Pengguna dapat menambah riwayat sendiri" ON public.riwayat_transaksi;
DROP POLICY IF EXISTS "Pengguna dapat memperbarui riwayat sendiri" ON public.riwayat_transaksi;
DROP POLICY IF EXISTS "Pengguna dapat menghapus riwayat sendiri" ON public.riwayat_transaksi;

-- Policy untuk `public.dompet_pelajar`
CREATE POLICY "Pengguna hanya dapat melihat dompet sendiri"
    ON public.dompet_pelajar
    FOR SELECT
    USING (auth.uid() = user_id);

CREATE POLICY "Pengguna dapat membuat dompet sendiri"
    ON public.dompet_pelajar
    FOR INSERT
    WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Pengguna dapat memperbarui dompet sendiri"
    ON public.dompet_pelajar
    FOR UPDATE
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Pengguna dapat menghapus dompet sendiri"
    ON public.dompet_pelajar
    FOR DELETE
    USING (auth.uid() = user_id);

-- Policy untuk `public.riwayat_transaksi`
CREATE POLICY "Pengguna hanya dapat melihat riwayat sendiri"
    ON public.riwayat_transaksi
    FOR SELECT
    USING (auth.uid() = user_id);

CREATE POLICY "Pengguna dapat menambah riwayat sendiri"
    ON public.riwayat_transaksi
    FOR INSERT
    WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Pengguna dapat memperbarui riwayat sendiri"
    ON public.riwayat_transaksi
    FOR UPDATE
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Pengguna dapat menghapus riwayat sendiri"
    ON public.riwayat_transaksi
    FOR DELETE
    USING (auth.uid() = user_id);

-- 5. FUNCTION & TRIGGER OTOMATIS SAAT USER BARU LOGIN GOOGLE (`handle_new_user`)
-- Dijalankan dengan SECURITY DEFINER agar memiliki hak akses menulis ke tabel public saat event auth.users terjadi.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    -- 1. Buat 1 baris dompet awal untuk user baru (Saldo saku: Rp0, Celengan: Rp0)
    INSERT INTO public.dompet_pelajar (
        user_id,
        sisa_saku,
        total_celengan,
        kas_senin_lunas,
        bawa_bekal_hari_ini,
        updated_at
    ) VALUES (
        NEW.id,
        0,
        0,
        false,
        false,
        now()
    )
    ON CONFLICT (user_id) DO NOTHING;

    RETURN NEW;
EXCEPTION
    WHEN OTHERS THEN
        -- Catat pesan error jika ada agar tidak memblokir proses registrasi user auth
        RAISE WARNING 'Gagal mengeksekusi handle_new_user: %', SQLERRM;
        RETURN NEW;
END;
$$;

-- Trigger pada event AFTER INSERT tabel auth.users
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_new_user();

-- Berikan hak akses skema public ke authenticated & anon users
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT ALL ON TABLE public.dompet_pelajar TO anon, authenticated;
GRANT ALL ON TABLE public.riwayat_transaksi TO anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;
